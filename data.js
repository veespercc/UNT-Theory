// ---------- Математические помощники ----------
function randInt(min, max) { return Math.floor(Math.random() * (max - min + 1)) + min; }
function pick(arr) { return arr[randInt(0, arr.length - 1)]; }
function gcd(a, b) { a = Math.abs(a); b = Math.abs(b); while (b) { [a, b] = [b, a % b]; } return a || 1; }
function simplifyFrac(num, den) {
  if (den < 0) { num = -num; den = -den; }
  const g = gcd(num, den) || 1;
  return { num: num / g, den: den / g };
}
function fracLatex(num, den) {
  const s = simplifyFrac(num, den);
  if (s.den === 1) return `${s.num}`;
  if (s.num < 0) return `-\\frac{${Math.abs(s.num)}}{${s.den}}`;
  return `\\frac{${s.num}}{${s.den}}`;
}
function factorial(n) { let r = 1; for (let i = 2; i <= n; i++) r *= i; return r; }
function nCr(n, k) { return Math.round(factorial(n) / (factorial(k) * factorial(n - k))); }
function signStr(n) { return n >= 0 ? '+' : '-'; }

