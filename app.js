function setMode(mode) {
  currentMode = mode;
  if (mode === 'theory') {
    modeTheoryBtn.classList.add('active');
    modeFormulasBtn.classList.remove('active');
  } else {
    modeFormulasBtn.classList.add('active');
    modeTheoryBtn.classList.remove('active');
  }
  render();
}

function showToast(text) {
  toast.textContent = text;
  toast.classList.add('show');
  setTimeout(() => toast.classList.remove('show'), 1600);
}

function toggleMastered(id) {
  if (mastered.includes(id)) {
    mastered = mastered.filter(x => x !== id);
  } else {
    mastered.push(id);
  }
  localStorage.setItem('unt_mastered_gen_v1', JSON.stringify(mastered));
  render();
}

function copyFormula(cardId) {
  const item = dataset.find(d => d.id === cardId);
  if (!item) return;
  const curIdx = activeSlideIndex[cardId] || 0;
  const latex = item.formulas[curIdx].latex;
  navigator.clipboard.writeText(latex);
  showToast(`Скопирована формула [${curIdx + 1}]`);
}

function toggleGenSolution(id) {
  const panel = document.getElementById(`gen-sol-${id}`);
  const btn = document.getElementById(`gen-btn-${id}`);
  if (panel) {
    panel.classList.toggle('show');
    btn.classList.toggle('open');
  }
}

function generateNewTask(id) {
  if (generators[id]) {
    generatedTasksState[id] = generators[id]();
    
    // Update DOM directly for instant response
    const widget = document.getElementById(`gen-widget-${id}`);
    if (widget) {
      const task = generatedTasksState[id];
      const promptEl = widget.querySelector('.gen-problem-prompt');
      const mathEl = widget.querySelector('.gen-math-display');
      const solPanel = widget.querySelector('.gen-solution-panel');
      const solBtn = widget.querySelector('.gen-spoiler-btn');

      if (promptEl) promptEl.textContent = task.prompt;
      if (mathEl) mathEl.innerHTML = `$$${task.latex}$$`;
      if (solBtn) solBtn.classList.remove('open');
      if (solPanel) {
        solPanel.classList.remove('show');
        solPanel.innerHTML = `
          ${task.steps.map(s => `<div class="gen-solution-step">${s}</div>`).join('')}
          <div class="gen-solution-answer">Ответ: ${task.ans}</div>
        `;
      }

      if (window.renderMathInElement) {
        renderMathInElement(widget, {
          delimiters: [
            {left: '$$', right: '$$', display: true},
            {left: '$', right: '$', display: false}
          ],
          throwOnError: false
        });
      }
      showToast('Сгенерирована новая задача');
    }
  }
}

function setSlide(cardId, idx) {
  const item = dataset.find(d => d.id === cardId);
  if (!item) return;
  const total = item.formulas.length;
  if (idx < 0) idx = 0;
  if (idx >= total) idx = total - 1;

  activeSlideIndex[cardId] = idx;

  const slider = document.getElementById(`slider-${cardId}`);
  if (slider) slider.style.transform = `translateX(-${idx * 100}%)`;

  const label = document.getElementById(`label-${cardId}`);
  if (label) {
    label.innerHTML = `<strong>${idx + 1}/${total}</strong> &bull; ${item.formulas[idx].name}`;
  }

  const prev = document.getElementById(`p-${cardId}`);
  const next = document.getElementById(`n-${cardId}`);
  if (prev) prev.disabled = (idx === 0);
  if (next) next.disabled = (idx === total - 1);

  const bars = document.querySelectorAll(`.bar-${cardId}`);
  bars.forEach((b, i) => b.classList.toggle('active', i === idx));
}

function prevSlide(cardId) {
  const cur = activeSlideIndex[cardId] || 0;
  setSlide(cardId, cur - 1);
}

function nextSlide(cardId) {
  const cur = activeSlideIndex[cardId] || 0;
  setSlide(cardId, cur + 1);
}

function updateProgress() {
  progVal.textContent = `${mastered.length}/${dataset.length}`;
}

