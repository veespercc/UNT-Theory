function showToast(text) {
  toast.textContent = text;
  toast.classList.add('show');
  setTimeout(() => toast.classList.remove('show'), 1600);
}

function toggleMastered(id) {
  if (mastered.includes(id)) {
    mastered = mastered.filter(x => x !== id);
  } else {
    mastered.push(id);
  }
  localStorage.setItem('unt_mastered_dual_v1', JSON.stringify(mastered));
  render();
}

function copyFormula(cardId) {
  const item = dataset.find(d => d.id === cardId);
  if (!item) return;
  const curIdx = activeSlideIndex[cardId] || 0;
  const latex = item.formulas[curIdx].latex;
  navigator.clipboard.writeText(latex);
  showToast(`Скопирована формула [${curIdx + 1}]`);
}

function toggleDisclosure(id) {
  const panel = document.getElementById(`panel-${id}`);
  const btn = document.getElementById(`d-btn-${id}`);
  if (panel) {
    panel.classList.toggle('show');
    btn.classList.toggle('open');
  }
}

function setSlide(cardId, idx) {
  const item = dataset.find(d => d.id === cardId);
  if (!item) return;
  const total = item.formulas.length;
  if (idx < 0) idx = 0;
  if (idx >= total) idx = total - 1;

  activeSlideIndex[cardId] = idx;

  const slider = document.getElementById(`slider-${cardId}`);
  if (slider) slider.style.transform = `translateX(-${idx * 100}%)`;

  const label = document.getElementById(`label-${cardId}`);
  if (label) {
    label.innerHTML = `<strong>${idx + 1}/${total}</strong> &bull; ${item.formulas[idx].name}`;
  }

  const prev = document.getElementById(`p-${cardId}`);
  const next = document.getElementById(`n-${cardId}`);
  if (prev) prev.disabled = (idx === 0);
  if (next) next.disabled = (idx === total - 1);

  const bars = document.querySelectorAll(`.bar-${cardId}`);
  bars.forEach((b, i) => b.classList.toggle('active', i === idx));
}

function prevSlide(cardId) {
  const cur = activeSlideIndex[cardId] || 0;
  setSlide(cardId, cur - 1);
}

function nextSlide(cardId) {
  const cur = activeSlideIndex[cardId] || 0;
  setSlide(cardId, cur + 1);
}

function updateProgress() {
  progVal.textContent = `${mastered.length}/${dataset.length}`;
}

