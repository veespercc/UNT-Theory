                        item.meaning.toLowerCase().includes(searchQuery) ||
                        item.tag.toLowerCase().includes(searchQuery) ||
                        item.trap.toLowerCase().includes(searchQuery) ||
                        (item.theory && item.theory.essence.toLowerCase().includes(searchQuery));
    return matchCat && matchSearch;
